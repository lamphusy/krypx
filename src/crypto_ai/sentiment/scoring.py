"""Offline-only synthetic scoring foundation; no model or network adapters.

The protocol is an extension seam, not permission to execute arbitrary adapters.
Only the sealed, scripted MockScorer is admitted by OfflineScoringEngine. Mock
byte tokens and artifact identities must never be presented as a real runtime.
"""

